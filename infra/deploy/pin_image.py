#!/usr/bin/env python3
"""Pin a built container image digest into images.auto.tfvars for platform or workloads root."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


def parse_existing_images(tfvars_path: Path) -> dict[str, str]:
    images: dict[str, str] = {}
    if not tfvars_path.exists():
        return images
    content = tfvars_path.read_text(encoding="utf-8")
    for match in re.finditer(r'"([^"]+)"\s*=\s*"([^"]+)"', content):
        images[match.group(1)] = match.group(2)
    return images


def render_tfvars(images: dict[str, str]) -> str:
    lines = [
        "# Auto-generated by infra/deploy/pin_image.py — DO NOT EDIT MANUALLY",
        "images = {",
    ]
    max_key_len = max((len(f'"{svc}"') for svc in images), default=0)
    for svc in sorted(images.keys()):
        quoted_key = f'"{svc}"'.ljust(max_key_len)
        lines.append(f'  {quoted_key} = "{images[svc]}"')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Pin service image digest in images.auto.tfvars")
    parser.add_argument("--root", choices=["platform", "workloads"], required=True)
    parser.add_argument("--service", required=True)
    parser.add_argument("--image", required=True)
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parents[2]
    tfvars_path = repo_root / "infra" / "terraform" / args.root / "images.auto.tfvars"
    tfvars_path.parent.mkdir(parents=True, exist_ok=True)

    images = parse_existing_images(tfvars_path)
    images[args.service] = args.image
    tfvars_path.write_text(render_tfvars(images), encoding="utf-8")
    print(f"[pin_image] Updated {tfvars_path}: {args.service} = {args.image}")


if __name__ == "__main__":
    main()
